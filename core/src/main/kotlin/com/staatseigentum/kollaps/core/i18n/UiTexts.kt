/**
 * The words that belong to the screens rather than to a content catalogue.
 *
 * Buttons, headings, the sentences that explain a mechanism, the empty-list apologies. They are
 * written where they are drawn, and where they are drawn is the app and desktop modules — which
 * `:core` cannot see and must never learn to. So they are listed here, and the list is kept honest
 * from the other side: `UiTextTest` reads those sources and fails on a `Lang.t` whose text is
 * missing from here, and on an entry here that nothing says any more.
 *
 * "Those sources" means both modules and every directory in them, not the screens alone. Reading
 * only `app/.../ui` is what let 5.0.0 ship a PC update card in German: it says "Alles aktuell."
 * from the desktop module, this list never saw it, [Texts] therefore never asked for it, and the
 * coverage test was green over an untranslated card.
 *
 * That is the whole reason this file is a list of bare strings and not a set of constants. A
 * constant would have to be referenced from the screen, which means the screen would read
 * `Texts.BUY` instead of `Lang.t("Kaufen")` — and then the interface source stops saying what it
 * puts on the screen, which is the one property that makes this codebase readable.
 *
 * Generated from the screens rather than written by hand — see `UiTextTest`, which rebuilds this
 * list from the sources and fails if it has drifted. A hand-kept copy of something a machine can
 * read is a copy that goes stale on the first busy afternoon.
 */
